#!/usr/bin/env python3
"""
Asymmetric Information Transfer Analysis

Tests the hypothesis: algorithms are perfect receivers of inherited state,
but LLMs are lossy receivers. This explains:
- Why LLM-first outperforms algo-first (direction effect)
- Why signal integration is weak
- Why the effect scales with task complexity

For each round played by an LLM, we measure:
1. How much prior state was generated by algorithm vs by the LLM itself
2. Information gain on that round
3. Constraint violation rate on that round
4. Whether inherited algo state degrades LLM performance

Similarly for algorithm rounds: does inherited LLM state degrade algo performance?
"""

import csv
import glob
import math
import os
import statistics
import sys
from collections import defaultdict
from pathlib import Path

PROJECT_ROOT = Path(__file__).parent.parent
WORDLIST_PATH = PROJECT_ROOT / "wordlist" / "wordlist.txt"
WORDLE_RESULTS = PROJECT_ROOT / "results" / "workshop"
MM_CLASSIC_RESULTS = PROJECT_ROOT / "results" / "mastermind" / "hybrids" / "classic"
MM_EXTENDED_RESULTS = PROJECT_ROOT / "results" / "mastermind" / "hybrids" / "extended"
LLM_ONLY_RESULTS = PROJECT_ROOT / "results" / "llms" / "raw data"
OUTPUT_DIR = PROJECT_ROOT / "analysis"


def load_wordlist():
    with open(WORDLIST_PATH) as f:
        return [w.strip().upper() for w in f if w.strip()]


def generate_wordle_feedback(guess, target):
    feedback = ["-"] * 5
    target_chars = list(target)
    guess_chars = list(guess)
    for i in range(5):
        if guess_chars[i] == target_chars[i]:
            feedback[i] = "G"
            target_chars[i] = None
            guess_chars[i] = None
    for i in range(5):
        if guess_chars[i] and guess_chars[i] in target_chars:
            feedback[i] = "Y"
            target_chars[target_chars.index(guess_chars[i])] = None
    return "".join(feedback)


def filter_wordle_candidates(candidates, guess, feedback):
    return [w for w in candidates if generate_wordle_feedback(guess, w) == feedback]


def check_wordle_violations(guess, feedback_history):
    """Check if a guess violates known constraints from prior feedback."""
    violations = 0
    known_greens = {}
    known_grays = set()
    known_yellows = defaultdict(set)  # position -> set of letters that must not be there

    for prev_guess, prev_feedback in feedback_history:
        for i, (ch, fb) in enumerate(zip(prev_guess, prev_feedback)):
            if fb == "G":
                known_greens[i] = ch
            elif fb == "Y":
                known_yellows[i].add(ch)
            elif fb == "-":
                # Only gray if letter doesn't appear as G or Y elsewhere
                is_elsewhere = any(
                    prev_feedback[j] in ("G", "Y") and prev_guess[j] == ch
                    for j in range(5) if j != i
                )
                if not is_elsewhere:
                    known_grays.add(ch)

    # Check violations
    for i, ch in enumerate(guess):
        # Green violation: known green position has different letter
        if i in known_greens and known_greens[i] != ch:
            violations += 1
        # Gray violation: using a letter known to be absent
        if ch in known_grays:
            violations += 1
        # Yellow violation: placing letter in position where it was yellow before
        if ch in known_yellows.get(i, set()):
            violations += 1

    return violations


def process_wordle_hybrids(wordlist):
    """Process all Wordle hybrid games, computing per-round info gain."""
    results = []

    # Process Group A, B, C, D configs
    csv_files = sorted(glob.glob(str(WORDLE_RESULTS / "group_*" / "*" / "raw_data" / "*.csv")))
    csv_files = [f for f in csv_files if "summary_" not in os.path.basename(f)]

    print(f"Found {len(csv_files)} Wordle hybrid CSV files")

    for csv_file in csv_files:
        fname = os.path.basename(csv_file)
        # Extract config from path
        parts = csv_file.split("/")
        group_idx = next(i for i, p in enumerate(parts) if p.startswith("group_"))
        group = parts[group_idx]
        config = parts[group_idx + 1]

        # Extract model from filename
        model = fname.replace(".csv", "")
        for prefix in [f"{config}_", "alternating_algorithm_first_", "alternating_llm_first_",
                       "constraint_filter_css_", "constraint_filter_voi_", "random_to_css_", "random_to_voi_"]:
            if model.startswith(prefix):
                model = model[len(prefix):]
                break
        # Strip timestamp suffix
        parts_m = model.rsplit("_", 2)
        if len(parts_m) >= 3 and parts_m[-1].isdigit() and parts_m[-2].isdigit():
            model = "_".join(parts_m[:-2])

        with open(csv_file) as f:
            reader = csv.DictReader(f)
            rows = list(reader)

        for row in rows:
            target = row.get("target_word", "").upper()
            if not target or len(target) != 5:
                continue

            won = row.get("won", "").lower() == "true"
            attempts = int(row.get("attempts", 0))

            candidates = list(wordlist)
            feedback_history = []

            for r in range(1, 7):
                guess = row.get(f"guess_{r}", "").strip().upper()
                feedback = row.get(f"feedback_{r}", "").strip()
                strategy = row.get(f"strategy_{r}", "").strip().upper()

                if not guess or not feedback or len(guess) != 5 or len(feedback) != 5:
                    break

                # Compute info gain
                candidates_before = len(candidates)
                entropy_before = math.log2(candidates_before) if candidates_before > 1 else 0

                candidates_after_list = filter_wordle_candidates(candidates, guess, feedback)
                candidates_after = max(len(candidates_after_list), 1)

                info_gain = math.log2(candidates_before / candidates_after) if candidates_before > candidates_after else 0

                # Check violations (only for rounds > 1)
                violation_count = check_wordle_violations(guess, feedback_history) if r > 1 else 0

                # Count how many prior rounds were played by each agent
                algo_prior_rounds = sum(1 for _, _, s in [(row.get(f"guess_{rr}", ""),
                                                            row.get(f"feedback_{rr}", ""),
                                                            row.get(f"strategy_{rr}", ""))
                                                           for rr in range(1, r)]
                                        if s and s.strip().upper() in ("CSS", "VOI"))
                llm_prior_rounds = sum(1 for _, _, s in [(row.get(f"guess_{rr}", ""),
                                                          row.get(f"feedback_{rr}", ""),
                                                          row.get(f"strategy_{rr}", ""))
                                                         for rr in range(1, r)]
                                       if s and s.strip().upper() == "LLM")

                # What fraction of inherited state came from algorithm?
                total_prior = algo_prior_rounds + llm_prior_rounds
                algo_state_fraction = algo_prior_rounds / total_prior if total_prior > 0 else 0

                results.append({
                    "domain": "wordle",
                    "config": f"{group}/{config}",
                    "model": model,
                    "game_number": row.get("game_number", ""),
                    "target": target,
                    "round": r,
                    "guess": guess,
                    "feedback": feedback,
                    "strategy": strategy,
                    "won": won,
                    "candidates_before": candidates_before,
                    "candidates_after": candidates_after,
                    "info_gain_bits": round(info_gain, 4),
                    "entropy_before": round(entropy_before, 4),
                    "violation_count": violation_count,
                    "algo_prior_rounds": algo_prior_rounds,
                    "llm_prior_rounds": llm_prior_rounds,
                    "algo_state_fraction": round(algo_state_fraction, 4),
                    "inherited_state": "algo" if algo_state_fraction > 0.5 else ("mixed" if 0 < algo_state_fraction <= 0.5 else "self"),
                })

                # Update state
                feedback_history.append((guess, feedback))
                candidates = candidates_after_list if candidates_after_list else candidates

    return results


def process_mastermind_hybrids(base_dir, domain_name):
    """Process Mastermind hybrid games using pre-computed candidates_N."""
    results = []

    csv_files = sorted(glob.glob(str(base_dir / "group_*" / "*" / "raw_data" / "*.csv")))
    csv_files = [f for f in csv_files if "summary_" not in os.path.basename(f)]

    print(f"Found {len(csv_files)} {domain_name} hybrid CSV files")

    max_rounds = 10 if "extended" in domain_name.lower() else 6

    for csv_file in csv_files:
        fname = os.path.basename(csv_file)
        parts = csv_file.split("/")
        group_idx = next(i for i, p in enumerate(parts) if p.startswith("group_"))
        group = parts[group_idx]
        config = parts[group_idx + 1]

        model = fname.replace(".csv", "")
        for prefix in [f"{config}_"]:
            if model.startswith(prefix):
                model = model[len(prefix):]
                break
        parts_m = model.rsplit("_", 2)
        if len(parts_m) >= 3 and parts_m[-1].isdigit() and parts_m[-2].isdigit():
            model = "_".join(parts_m[:-2])

        with open(csv_file) as f:
            reader = csv.DictReader(f)
            rows = list(reader)

        for row in rows:
            target = row.get("target_code", "").upper()
            won = row.get("won", "").lower() == "true"

            prev_candidates = None

            for r in range(1, max_rounds + 1):
                guess = row.get(f"guess_{r}", "").strip()
                feedback = row.get(f"feedback_{r}", "").strip()
                strategy = row.get(f"strategy_{r}", "").strip().upper()
                candidates_str = row.get(f"candidates_{r}", "")

                if not guess or not feedback or not strategy:
                    break

                # Skip invalid guesses
                if feedback == "INVALID":
                    continue

                try:
                    candidates_after = int(candidates_str)
                except (ValueError, TypeError):
                    candidates_after = None

                # Compute info gain from candidates
                if prev_candidates is not None and candidates_after is not None and candidates_after > 0:
                    info_gain = math.log2(prev_candidates / candidates_after) if prev_candidates > candidates_after else 0
                    entropy_before = math.log2(prev_candidates) if prev_candidates > 1 else 0
                else:
                    info_gain = 0
                    entropy_before = 0

                algo_prior_rounds = sum(1 for rr in range(1, r)
                                        if row.get(f"strategy_{rr}", "").strip().upper() in ("CSS", "VOI")
                                        and row.get(f"feedback_{rr}", "").strip() != "INVALID")
                llm_prior_rounds = sum(1 for rr in range(1, r)
                                       if row.get(f"strategy_{rr}", "").strip().upper() == "LLM"
                                       and row.get(f"feedback_{rr}", "").strip() != "INVALID")

                total_prior = algo_prior_rounds + llm_prior_rounds
                algo_state_fraction = algo_prior_rounds / total_prior if total_prior > 0 else 0

                results.append({
                    "domain": domain_name,
                    "config": f"{group}/{config}",
                    "model": model,
                    "game_number": row.get("game_number", ""),
                    "target": target,
                    "round": r,
                    "guess": guess,
                    "feedback": feedback,
                    "strategy": strategy,
                    "won": won,
                    "candidates_before": prev_candidates if prev_candidates else 0,
                    "candidates_after": candidates_after if candidates_after else 0,
                    "info_gain_bits": round(info_gain, 4),
                    "entropy_before": round(entropy_before, 4),
                    "violation_count": 0,  # Not computed for MM
                    "algo_prior_rounds": algo_prior_rounds,
                    "llm_prior_rounds": llm_prior_rounds,
                    "algo_state_fraction": round(algo_state_fraction, 4),
                    "inherited_state": "algo" if algo_state_fraction > 0.5 else ("mixed" if 0 < algo_state_fraction <= 0.5 else "self"),
                })

                if candidates_after is not None:
                    prev_candidates = candidates_after

    return results


def analyze_asymmetric_transfer(all_results):
    """Core analysis: do LLMs degrade when receiving algo state vs their own?"""

    print(f"\n{'='*70}")
    print("ASYMMETRIC INFORMATION TRANSFER ANALYSIS")
    print(f"{'='*70}")
    print(f"Total round records: {len(all_results)}")

    # Only look at rounds > 1 (where there IS inherited state)
    r2plus = [r for r in all_results if r["round"] > 1]
    print(f"Rounds 2+ (with inherited state): {len(r2plus)}")

    for domain in sorted(set(r["domain"] for r in r2plus)):
        domain_rows = [r for r in r2plus if r["domain"] == domain]

        print(f"\n{'='*70}")
        print(f"  DOMAIN: {domain.upper()}")
        print(f"{'='*70}")

        # === LLM rounds: inherited algo state vs inherited self state ===
        llm_rounds = [r for r in domain_rows if r["strategy"] == "LLM"]

        # Split by what state they inherited
        llm_after_algo = [r for r in llm_rounds if r["inherited_state"] == "algo"]
        llm_after_self = [r for r in llm_rounds if r["inherited_state"] == "self"]
        llm_after_mixed = [r for r in llm_rounds if r["inherited_state"] == "mixed"]

        print(f"\n  --- LLM Rounds (n={len(llm_rounds)}) ---")
        print(f"  After inheriting algo state:  {len(llm_after_algo)}")
        print(f"  After inheriting own state:   {len(llm_after_self)}")
        print(f"  After mixed state:            {len(llm_after_mixed)}")

        for label, group in [("inherited_algo", llm_after_algo),
                              ("inherited_self", llm_after_self),
                              ("inherited_mixed", llm_after_mixed)]:
            if not group:
                continue
            ig = [r["info_gain_bits"] for r in group]
            ent = [r["entropy_before"] for r in group]
            print(f"\n  LLM [{label}] (n={len(group)}):")
            print(f"    Info gain:      mean={statistics.mean(ig):.3f}  median={statistics.median(ig):.3f}")
            print(f"    Entropy before: mean={statistics.mean(ent):.3f}")
            if domain == "wordle":
                viol = [r["violation_count"] for r in group]
                viol_rate = sum(1 for v in viol if v > 0) / len(viol) * 100
                print(f"    Violation rate: {viol_rate:.1f}%  mean_count={statistics.mean(viol):.2f}")

        # === Algorithm rounds: inherited LLM state vs inherited self state ===
        algo_rounds = [r for r in domain_rows if r["strategy"] in ("CSS", "VOI")]

        algo_after_llm = [r for r in algo_rounds if r["inherited_state"] == "self" and r["llm_prior_rounds"] > 0]
        # Actually: algo after LLM = algo rounds where prior state is mostly from LLM
        algo_after_llm = [r for r in algo_rounds if r["algo_state_fraction"] < 0.5 and r["llm_prior_rounds"] > 0]
        algo_after_self = [r for r in algo_rounds if r["algo_state_fraction"] > 0.5]
        algo_after_mixed_or_llm = [r for r in algo_rounds if r["algo_state_fraction"] <= 0.5]

        print(f"\n  --- Algorithm Rounds (n={len(algo_rounds)}) ---")
        print(f"  After inheriting LLM state:   {len(algo_after_mixed_or_llm)}")
        print(f"  After inheriting own state:    {len(algo_after_self)}")

        for label, group in [("inherited_llm_state", algo_after_mixed_or_llm),
                              ("inherited_algo_state", algo_after_self)]:
            if not group:
                continue
            ig = [r["info_gain_bits"] for r in group]
            ent = [r["entropy_before"] for r in group]
            print(f"\n  Algorithm [{label}] (n={len(group)}):")
            print(f"    Info gain:      mean={statistics.mean(ig):.3f}  median={statistics.median(ig):.3f}")
            print(f"    Entropy before: mean={statistics.mean(ent):.3f}")

    # === Normalized analysis: info gain per bit of entropy ===
    print(f"\n{'='*70}")
    print("NORMALIZED EFFICIENCY: Info Gain / Entropy Before")
    print(f"{'='*70}")
    print("(Controls for different starting difficulty)")

    for domain in sorted(set(r["domain"] for r in r2plus)):
        domain_rows = [r for r in r2plus if r["domain"] == domain]
        print(f"\n  --- {domain.upper()} ---")

        for agent in ["LLM", "ALGO"]:
            if agent == "LLM":
                agent_rows = [r for r in domain_rows if r["strategy"] == "LLM" and r["entropy_before"] > 0]
            else:
                agent_rows = [r for r in domain_rows if r["strategy"] in ("CSS", "VOI") and r["entropy_before"] > 0]

            if not agent_rows:
                continue

            after_algo = [r for r in agent_rows if r["algo_state_fraction"] > 0.5]
            after_llm = [r for r in agent_rows if r["algo_state_fraction"] < 0.5 and r["llm_prior_rounds"] > 0]
            after_self_only = [r for r in agent_rows if
                               (agent == "LLM" and r["llm_prior_rounds"] > 0 and r["algo_prior_rounds"] == 0) or
                               (agent == "ALGO" and r["algo_prior_rounds"] > 0 and r["llm_prior_rounds"] == 0)]

            for label, group in [("after_algo_state", after_algo),
                                  ("after_llm_state", after_llm),
                                  ("after_own_state_only", after_self_only)]:
                if not group:
                    continue
                efficiency = [r["info_gain_bits"] / r["entropy_before"] for r in group if r["entropy_before"] > 0]
                if efficiency:
                    print(f"  {agent:>4} [{label:<20}] (n={len(efficiency):>5}): "
                          f"efficiency={statistics.mean(efficiency):.4f}  "
                          f"(= {statistics.mean(efficiency)*100:.1f}% of remaining entropy captured)")

    # === Per-round degradation curve ===
    print(f"\n{'='*70}")
    print("PER-ROUND LLM PERFORMANCE BY INHERITED STATE SOURCE")
    print(f"{'='*70}")

    for domain in sorted(set(r["domain"] for r in r2plus)):
        domain_rows = [r for r in r2plus if r["domain"] == domain]
        llm_rows = [r for r in domain_rows if r["strategy"] == "LLM"]

        print(f"\n  --- {domain.upper()} ---")
        print(f"  {'Round':<6} {'After Algo (n)':<16} {'IG_algo':<10} {'After Self (n)':<16} {'IG_self':<10} {'Delta':<10}")
        print(f"  {'-'*68}")

        max_round = 10 if "extended" in domain.lower() else 6
        for rd in range(2, max_round + 1):
            rd_rows = [r for r in llm_rows if r["round"] == rd]
            after_algo = [r for r in rd_rows if r["algo_prior_rounds"] > 0 and r["llm_prior_rounds"] == 0]
            after_self = [r for r in rd_rows if r["llm_prior_rounds"] > 0 and r["algo_prior_rounds"] == 0]

            ig_algo = statistics.mean([r["info_gain_bits"] for r in after_algo]) if after_algo else float('nan')
            ig_self = statistics.mean([r["info_gain_bits"] for r in after_self]) if after_self else float('nan')

            delta = ig_self - ig_algo if not (math.isnan(ig_algo) or math.isnan(ig_self)) else float('nan')

            print(f"  {rd:<6} {len(after_algo):>5}            {ig_algo:>8.3f}  {len(after_self):>5}            {ig_self:>8.3f}  {delta:>+8.3f}")


def save_results(all_results):
    """Save per-round data to CSV."""
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    outpath = OUTPUT_DIR / "asymmetric_transfer_per_round.csv"
    with open(outpath, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=all_results[0].keys())
        writer.writeheader()
        writer.writerows(all_results)
    print(f"\nSaved {len(all_results)} rows to {outpath}")

    # Summary by domain x agent x inherited_state
    summary_rows = []
    for domain in sorted(set(r["domain"] for r in all_results)):
        r2plus = [r for r in all_results if r["domain"] == domain and r["round"] > 1]
        for agent_type in ["LLM", "CSS", "VOI"]:
            if agent_type == "LLM":
                agent_rows = [r for r in r2plus if r["strategy"] == "LLM"]
            else:
                agent_rows = [r for r in r2plus if r["strategy"] == agent_type]
            if not agent_rows:
                continue

            for state_src in ["algo", "self", "mixed"]:
                group = [r for r in agent_rows if r["inherited_state"] == state_src]
                if not group:
                    continue
                ig = [r["info_gain_bits"] for r in group]
                ent = [r["entropy_before"] for r in group if r["entropy_before"] > 0]
                eff = [r["info_gain_bits"] / r["entropy_before"] for r in group if r["entropy_before"] > 0]
                summary_rows.append({
                    "domain": domain,
                    "agent": agent_type,
                    "inherited_state": state_src,
                    "n": len(group),
                    "mean_info_gain": round(statistics.mean(ig), 4) if ig else 0,
                    "median_info_gain": round(statistics.median(ig), 4) if ig else 0,
                    "mean_entropy_before": round(statistics.mean(ent), 4) if ent else 0,
                    "mean_efficiency": round(statistics.mean(eff), 4) if eff else 0,
                })

    summary_path = OUTPUT_DIR / "asymmetric_transfer_summary.csv"
    with open(summary_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=summary_rows[0].keys())
        writer.writeheader()
        writer.writerows(summary_rows)
    print(f"Saved summary to {summary_path}")


def main():
    wordlist = load_wordlist()
    print(f"Loaded {len(wordlist)} words")

    all_results = []

    # Process Wordle (need to compute candidates)
    wordle_results = process_wordle_hybrids(wordlist)
    all_results.extend(wordle_results)
    print(f"Wordle: {len(wordle_results)} round records")

    # Process Mastermind Classic
    mm_classic = process_mastermind_hybrids(MM_CLASSIC_RESULTS, "mm_classic")
    all_results.extend(mm_classic)
    print(f"MM Classic: {len(mm_classic)} round records")

    # Process Mastermind Extended
    mm_extended = process_mastermind_hybrids(MM_EXTENDED_RESULTS, "mm_extended")
    all_results.extend(mm_extended)
    print(f"MM Extended: {len(mm_extended)} round records")

    print(f"\nTotal: {len(all_results)} round records across all domains")

    # Run analysis
    analyze_asymmetric_transfer(all_results)

    # Save
    save_results(all_results)


if __name__ == "__main__":
    main()
